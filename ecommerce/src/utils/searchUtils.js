export const normalizarTexto = (texto) => {
  if (!texto) return '';
  return texto
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();
};

export const buscarProductos = (productos, terminoBusqueda) => {
  if (!terminoBusqueda || terminoBusqueda.trim() === '') return productos;

  const terminoLimpio = normalizarTexto(terminoBusqueda);

  let terminosAlineados = [terminoLimpio];

  Object.keys(diccionarioBusqueda).forEach(key => {
    const keyNormalizado = normalizarTexto(key);
    if (terminoLimpio.includes(keyNormalizado) || keyNormalizado.includes(terminoLimpio)) {
      terminosAlineados = [...terminosAlineados, ...diccionarioBusqueda[key]];
    }
  });

  const terminosUnicos = [...new Set(terminosAlineados)];

  return productos.filter(producto => {
    const nombre = normalizarTexto(producto.nombre);
    const categoria = normalizarTexto(producto.categoria);
    const descripcion = normalizarTexto(producto.descripcion);

    return terminosUnicos.some(termino =>
      nombre.includes(termino) ||
      categoria.includes(termino) ||
      descripcion.includes(termino)
    );
  });
};
